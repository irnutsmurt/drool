// --- agent binaries served to new hosts ---

// Binary is an agent binary the controller can hand out for installation.
type Binary struct {
	Path   string
	Arch   string
	SHA256 string
	Size   int64
}

var binCache sync.Map // path → Binary (keyed with mtime)

func (s *Service) binariesDir() string {
	if s.cfg.BinariesDir != "" {
		return s.cfg.BinariesDir
	}
	exe, err := os.Executable()
	if err != nil {
		return "."
	}
	exe, _ = filepath.EvalSymlinks(exe)
	return filepath.Dir(exe)
}

// AgentBinary returns the agent binary for linux/arch.
func (s *Service) AgentBinary(arch string) (*Binary, error) {
	switch arch {
	case "amd64", "arm64":
	default:
		return nil, fmt.Errorf("no agent build for architecture %q (amd64 and arm64 are supported)", arch)
	}
	p := filepath.Join(s.binariesDir(), "drool-agent-linux-"+arch)
	fi, err := os.Stat(p)
	if err != nil {
		return nil, fmt.Errorf("the agent binary for linux/%s is not installed on the controller (%s)", arch, p)
	}
	key := fmt.Sprintf("%s|%d|%d", p, fi.Size(), fi.ModTime().UnixNano())
	if b, ok := binCache.Load(key); ok {
		bb := b.(Binary)
		return &bb, nil
	}
	f, err := os.Open(p)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	h := sha256.New()
	n, err := io.Copy(h, f)
	if err != nil {
		return nil, err
	}
	b := Binary{Path: p, Arch: arch, SHA256: hex.EncodeToString(h.Sum(nil)), Size: n}
	binCache.Store(key, b)
	return &b, nil
}

// InstallScript renders the shell installer for a manual installation.
// base is the controller's web URL, pin the web TLS public key pin
// ("sha256//…", empty when the web certificate is publicly trusted).
// The script verifies the downloaded binary's checksum and then runs
// `drool-agent install`, which pins the Agent Root CA from the token: the
// agent never relies on web TLS trust to authenticate the controller.
func (s *Service) InstallScript(base, pin string) string {
	sums := map[string]string{}
	for _, a := range []string{"amd64", "arm64"} {
		if b, err := s.AgentBinary(a); err == nil {
			sums[a] = b.SHA256
		}
	}
	curl := "curl -fsSL"
	if pin != "" {
		curl += " -k --pinnedpubkey '" + pin + "'"
	}
	var b strings.Builder
	fmt.Fprintf(&b, `#!/bin/sh
# DROOL agent installer, generated by the controller at %s.
#   usage: sh install.sh --token TOKEN [--preset monitor|managed|full] [--trust-release-key FILE]
set -eu
TOKEN="" PRESET="" KEY=""
while [ $# -gt 0 ]; do
  case "$1" in
    --token) TOKEN=$2; shift 2;;
    --preset) PRESET=$2; shift 2;;
    --trust-release-key) KEY=$2; shift 2;;
    *) echo "unknown option: $1" >&2; exit 2;;
  esac
done
[ -n "$TOKEN" ] || { echo "--token is required" >&2; exit 2; }
[ "$(id -u)" = 0 ] || { echo "run this as root (pipe it to sudo sh -s -- ...)" >&2; exit 1; }
case "$(uname -m)" in
  x86_64|amd64) ARCH=amd64; SUM='%s';;
  aarch64|arm64) ARCH=arm64; SUM='%s';;
  *) echo "unsupported architecture: $(uname -m)" >&2; exit 1;;
esac
[ -n "$SUM" ] || { echo "the controller has no agent build for $ARCH" >&2; exit 1; }
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
echo "Downloading drool-agent for linux/$ARCH..."
%s -o "$TMP/drool-agent" '%s/agent/download/linux-'"$ARCH"
echo "$SUM  $TMP/drool-agent" | sha256sum -c - >/dev/null || { echo "checksum mismatch: refusing to install" >&2; exit 1; }
chmod 0755 "$TMP/drool-agent"
set -- install --token-file -
[ -z "$PRESET" ] || set -- "$@" --preset "$PRESET"
[ -z "$KEY" ] || set -- "$@" --trust-release-key "$KEY"
printf '%%s\n' "$TOKEN" | "$TMP/drool-agent" "$@"
`, time.Now().UTC().Format(time.RFC3339), sums["amd64"], sums["arm64"], curl, strings.TrimRight(base, "/"))
	return b.String()
}

// InstallCommand is the one-liner shown in the UI.
func InstallCommand(base, pin, token, preset string) string {
	curl := "curl -fsSL"
	if pin != "" {
		curl += " -k --pinnedpubkey '" + pin + "'"
	}
	cmd := fmt.Sprintf("%s '%s/agent/install.sh' | sudo sh -s -- --token '%s'", curl, strings.TrimRight(base, "/"), token)
	if preset != "" {
		cmd += " --preset " + preset
	}
	return cmd
}

// --- installation over a trusted SSH connection ---

// InstallOptions describe an agent installation over SSH.
type InstallOptions struct {
	HostID     string
	Preset     string
	ReleaseKey string // optional release public key line to trust
	UserID     string
	WebHost    string
}

// InstallViaSSH installs and enrolls the agent on an SSH-managed host,
// using the host's pinned SSH connection: upload the binary as the login
// user, then run `drool-agent install` as root with a host-bound token on
// stdin. The host becomes "agent preferred, SSH fallback".
func (s *Service) InstallViaSSH(ctx context.Context, o InstallOptions, out io.Writer) error {
	logf := func(format string, a ...any) { fmt.Fprintf(out, format+"\n", a...) }
	h, err := s.st.R.GetHost(ctx, o.HostID)
	if err != nil {
		return err
	}
	if h.SshConfigured == 0 {
		return errors.New("this host has no SSH access; install the agent manually")
	}
	if _, err := s.st.R.GetLiveIdentityForHost(ctx, o.HostID); err == nil {
		return errors.New("this host already has an agent identity; revoke it first to install a new agent")
	}
	if _, err := agentcaps.Preset(o.Preset); err != nil {
		return err
	}
	if o.ReleaseKey != "" {
		if _, err := release.ParsePublicKey(o.ReleaseKey); err != nil {
			return err
		}
	}
	logf("Checking the host over its pinned SSH connection...")
	r, err := s.inv.RunOnHost(ctx, o.HostID, "uname -m", nil, false, time.Minute)
	if err != nil {
		return fmt.Errorf("SSH: %w", err)
	}
	arch := map[string]string{"x86_64": "amd64", "amd64": "amd64", "aarch64": "arm64", "arm64": "arm64"}[strings.TrimSpace(string(r.Stdout))]
	bin, err := s.AgentBinary(arch)
	if err != nil {
		return err
	}
	data, err := os.ReadFile(bin.Path)
	if err != nil {
		return err
	}
	logf("Uploading drool-agent (linux/%s, %d MB, sha256 %.16s)...", arch, bin.Size>>20, bin.SHA256)
	r, err = s.inv.RunOnHost(ctx, o.HostID, `d=$(mktemp -d "${TMPDIR:-/tmp}/drool-agent-install.XXXXXXXX") && cat > "$d/drool-agent" && chmod 0755 "$d/drool-agent" && sha256sum "$d/drool-agent" && echo "$d"`, data, false, 5*time.Minute)
	if err != nil || r.ExitCode != 0 {
		return fmt.Errorf("upload failed: %v %s", err, strings.TrimSpace(string(r.Stderr)))
	}
	lines := strings.Split(strings.TrimSpace(string(r.Stdout)), "\n")
	dir := strings.TrimSpace(lines[len(lines)-1])
	if !strings.Contains(lines[0], bin.SHA256) || !strings.Contains(dir, "/drool-agent-install.") {
		return errors.New("the uploaded binary's checksum does not match")
	}
	defer s.inv.RunOnHost(context.WithoutCancel(ctx), o.HostID, "rm -rf -- "+hostops.ShQuote(dir), nil, false, time.Minute)
	tok, err := s.CreateToken(ctx, TokenOptions{Description: "installed over SSH", HostID: o.HostID, Preset: o.Preset,
		TTL: 15 * time.Minute, UserID: o.UserID, WebHost: o.WebHost})
	if err != nil {
		return err
	}
	cmd := hostops.ShQuote(dir+"/drool-agent") + " install --token-file - --preset " + hostops.ShQuote(o.Preset)
	stdin := []byte(tok.Token + "\n")
	if o.ReleaseKey != "" {
		if _, err := s.inv.RunOnHost(ctx, o.HostID, "cat > "+hostops.ShQuote(dir+"/release.pub"), []byte(o.ReleaseKey+"\n"), false, time.Minute); err != nil {
			return err
		}
		cmd += " --trust-release-key " + hostops.ShQuote(dir+"/release.pub")
	}
	logf("Installing and enrolling as root (agent endpoint %s)...", strings.Join(tok.Endpoints, ", "))
	r, err = s.inv.RunOnHost(ctx, o.HostID, cmd, stdin, true, 3*time.Minute)
	if r != nil {
		out.Write(r.Stdout)
		out.Write(r.Stderr)
	}
	if err != nil {
		return err
	}
	if r.ExitCode != 0 {
		return fmt.Errorf("drool-agent install exited with status %d", r.ExitCode)
	}
	logf("Waiting for the agent to connect...")
	deadline := time.Now().Add(90 * time.Second)
	for time.Now().Before(deadline) {
		if _, ok := s.SessionFor(o.HostID); ok {
			logf("The agent is connected. This host is now managed through the agent, with SSH as fallback.")
			s.audit.Record(ctx, audit.Event{Action: "agent.install", TargetType: "host", TargetID: o.HostID,
				Details: map[string]any{"preset": o.Preset, "arch": arch, "binary_sha256": bin.SHA256, "release_key": o.ReleaseKey != ""}})
			return nil
		}
		select {
		case <-ctx.Done():
			return ctx.Err()
		case <-time.After(time.Second):
		}
	}
	return errors.New("the agent was installed but has not connected yet; check `systemctl status drool-agent` on the host and that it can reach the controller's agent port")
}
