// Package ids generates prefixed, time-sortable identifiers such as
// "host_01J9ZK3Q4M8V6W2X5Y7Z0A1B2C".
package ids

import (
	"strings"

	"github.com/oklog/ulid/v2"
)

// Prefixes for each object type. Keep these stable; they appear in URLs,
// logs and audit records.
const (
	User           = "usr"
	Token          = "tok"
	Audit          = "aud"
	Request        = "req"
	Host           = "host"
	Group          = "grp"
	Secret         = "sec"
	HostKey        = "hk"
	Job            = "job"
	SetupCode      = "setup"
	FileDeployment = "fdep"
)

// New returns a new identifier with the given prefix. IDs generated by one
// process are strictly increasing, so they sort in creation order.
func New(prefix string) string {
	return prefix + "_" + strings.ToLower(ulid.Make().String())
}

// HasPrefix reports whether id was generated with prefix.
func HasPrefix(id, prefix string) bool {
	return strings.HasPrefix(id, prefix+"_")
}
